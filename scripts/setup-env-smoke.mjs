/**
 * Interactive wizard: writes repo-root `.env.smoke` from prompts (no manual file editing).
 *
 * Usage: npm run beta:smoke:setup
 */

import readline from "node:readline/promises";
import fs from "node:fs";
import path from "node:path";
import { stdin as input, stdout as output } from "node:process";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const outPath = path.join(root, ".env.smoke");

const DEFAULT_REF = "wslymzcbbevnoybbsbgq";

function maskEchoQuestion(rl, promptText) {
  return new Promise((resolve, reject) => {
    output.write(promptText);
    if (!input.isTTY) {
      return rl.question("").then(resolve).catch(reject);
    }
    rl.pause();
    input.setRawMode(true);
    input.resume();
    input.setEncoding("utf8");
    let buf = "";
    let cleaned = false;
    const cleanup = () => {
      if (cleaned) return;
      cleaned = true;
      try {
        input.setRawMode(false);
      } catch {
        /* ignore */
      }
      input.removeListener("data", onData);
      rl.resume();
    };
    const onData = (chunk) => {
      for (const key of chunk) {
        const code = key.charCodeAt(0);
        if (key === "\n" || key === "\r" || code === 4) {
          cleanup();
          output.write("\n");
          resolve(buf);
          return;
        }
        if (code === 3) {
          cleanup();
          reject(new Error("interrupted"));
          return;
        }
        if (key === "\u007f" || key === "\b") {
          buf = buf.slice(0, -1);
          output.write("\b \b");
        } else {
          buf += key;
          output.write("*");
        }
      }
    };
    input.on("data", onData);
  });
}

async function main() {
  const rl = readline.createInterface({ input, output });

  output.write("\n=== StorkBin .env.smoke setup ===\n");
  output.write("Creates .env.smoke at the repo root (gitignored). Ctrl+C to abort.\n\n");

  const projectRef = (
    await rl.question(`Supabase project ref [${DEFAULT_REF}]: `)
  ).trim() || DEFAULT_REF;
  const supabaseUrl = `https://${projectRef}.supabase.co`;

  output.write("Paste Supabase service_role key (input hidden).\n");
  const serviceRole = (await maskEchoQuestion(rl, "SUPABASE_SERVICE_ROLE_KEY: ")).trim();
  if (!serviceRole) {
    output.write("Service role key is required.\n");
    process.exit(1);
  }

  const anon = (await rl.question("Supabase anon key (optional; needed for email/password admin login): ")).trim();

  output.write("\nAdmin for JWT-protected edge checks:\n");
  output.write("  1 = paste ADMIN_SMOKE_JWT (from browser session)\n");
  output.write("  2 = email + password sign-in (needs anon key)\n");
  const mode = (await rl.question("Choose 1 or 2 [1]: ")).trim() || "1";

  let adminJwt = "";
  let adminEmail = "";
  let adminPassword = "";

  if (mode === "2") {
    adminEmail = (await rl.question("Admin email: ")).trim();
    if (!adminEmail) {
      output.write("Email required for mode 2.\n");
      process.exit(1);
    }
    if (!anon) {
      output.write("Anon key is required for mode 2. Re-run and paste anon key, or use mode 1.\n");
      process.exit(1);
    }
    output.write("Admin password (input hidden).\n");
    adminPassword = (await maskEchoQuestion(rl, "ADMIN_SMOKE_PASSWORD: ")).trim();
    if (!adminPassword) {
      output.write("Password required for mode 2.\n");
      process.exit(1);
    }
  } else {
    output.write("Paste access_token (long string). Input shown (easier to paste).\n");
    adminJwt = (await rl.question("ADMIN_SMOKE_JWT: ")).trim();
    if (!adminJwt) {
      output.write("JWT required for mode 1.\n");
      process.exit(1);
    }
  }

  output.write("\nStripe (optional; enables API + webhook URL checks in beta:smoke).\n");
  const stripe = (await rl.question("Stripe secret key (sk_test_...), or Enter to skip: ")).trim();
  const priceId = stripe
    ? (await rl.question("STRIPE_BIN_MONTHLY_PRICE_ID (price_...), or Enter to skip: ")).trim()
    : "";

  let forwardingOnly = "0";
  if (stripe) {
    output.write("\nStripe → Supabase webhooks:\n");
    output.write("  1 = I use Stripe Dashboard webhook URL(s) to Supabase (smoke will verify URL)\n");
    output.write("  2 = I use `stripe listen` only (skip Dashboard URL check)\n");
    const wh = (await rl.question("Choose 1 or 2 [2]: ")).trim() || "2";
    forwardingOnly = wh === "1" ? "0" : "1";
  }

  const lines = [
    "# Generated by npm run beta:smoke:setup — do not commit.",
    "",
    "SUPABASE_PROJECT_REF=" + projectRef,
    "SUPABASE_URL=" + supabaseUrl,
    "SUPABASE_SERVICE_ROLE_KEY=" + serviceRole,
  ];

  if (anon) lines.push("SUPABASE_ANON_KEY=" + anon);

  if (mode === "2") {
    lines.push("ADMIN_SMOKE_EMAIL=" + adminEmail);
    lines.push("ADMIN_SMOKE_PASSWORD=" + adminPassword);
    lines.push("ADMIN_SMOKE_JWT=");
  } else {
    lines.push("ADMIN_SMOKE_JWT=" + adminJwt);
    lines.push("# ADMIN_SMOKE_EMAIL=");
    lines.push("# ADMIN_SMOKE_PASSWORD=");
  }

  if (stripe) {
    lines.push("");
    lines.push("STRIPE_SECRET_KEY=" + stripe);
    if (priceId) lines.push("STRIPE_BIN_MONTHLY_PRICE_ID=" + priceId);
    lines.push("STRIPE_FORWARDING_ONLY=" + forwardingOnly);
  }

  lines.push("", "# Optional: npm run beta:smoke:stripe — checks Stripe CLI on PATH", "# STRIPE_CLI=1");

  if (fs.existsSync(outPath)) {
    const ok = (await rl.question("\n.env.smoke already exists. Overwrite? (y/N): ")).trim().toLowerCase();
    if (ok !== "y" && ok !== "yes") {
      output.write("Aborted (no changes).\n");
      await rl.close();
      process.exit(0);
    }
  }

  fs.writeFileSync(outPath, lines.join("\n") + "\n", "utf8");
  output.write(`\nWrote ${outPath}\n`);
  output.write("\nNext (copy/paste):\n  npm run beta:smoke\n  npm run beta:smoke:stripe   # optional Stripe CLI check\n");

  await rl.close();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
